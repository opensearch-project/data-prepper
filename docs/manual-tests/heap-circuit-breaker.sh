phase_check_prereqs() {
    section "Checking prerequisites"
    local missing=0 cmd
    for cmd in docker curl awk grep sed timeout $($TLS && echo openssl || true); do
        command -v "$cmd" >/dev/null 2>&1 || { printf '%s missing: %s%s\n' "$C_RED" "$cmd" "$C_RESET" >&2; missing=$((missing + 1)); }
    done
    if ! command -v telemetrygen >/dev/null 2>&1; then
        printf '%s missing: telemetrygen%s\n' "$C_RED" "$C_RESET" >&2
        printf '   install: %sgo install github.com/open-telemetry/opentelemetry-collector-contrib/cmd/telemetrygen@latest%s\n' "$C_DIM" "$C_RESET" >&2
        missing=$((missing + 1))
    fi
    (( missing == 0 )) || die "$missing prerequisite(s) missing"
    docker info >/dev/null 2>&1 || die "Docker daemon not reachable"
    if docker network ls --format '{{.Name}}' | grep -qx "$NET_NAME"; then
        die "Network $NET_NAME already exists (previous run?). Run: $0 --cleanup"
    fi
    log "Source: $SOURCE ($PLUGIN), nodes: $NODE_COUNT$( (( NODE_COUNT == 3 )) && echo ", scenario: $SCENARIO"). Output: $OUT_DIR"
}

phase_build() {
    section "Building Data Prepper (${INSTALL_TASK})"
    ( cd "$REPO_ROOT" && ./gradlew ":release:archives:linux:${INSTALL_TASK}" )
}

phase_locate_dp_home() {
    local version
    version="$(grep '^version=' "$REPO_ROOT/gradle.properties" | cut -d= -f2)"
    DP_HOME="$REPO_ROOT/release/archives/linux/build/install/opensearch-data-prepper-${version}-linux-${ARCH}"
    readonly DP_HOME
    [[ -d "$DP_HOME/lib" ]] || die "DP_HOME not found: $DP_HOME (run without --skip-build first)"
    log "DP_HOME=$DP_HOME"
}

phase_start_opensearch() {
    section "Starting network and single-node OpenSearch"
    rm -rf "$OUT_DIR"; mkdir -p "$OUT_DIR"
    docker network create --subnet "${NET_PREFIX}.0/24" "$NET_NAME" >/dev/null
    docker run -d --name "$OS_CONTAINER" --network "$NET_NAME" --ip "$OS_IP" \
        -e discovery.type=single-node -e DISABLE_SECURITY_PLUGIN=true \
        -e "OPENSEARCH_JAVA_OPTS=-Xms512m -Xmx512m" "$OS_IMAGE" >/dev/null
    docker pull -q "$JRE_IMAGE" >/dev/null
    local i
    for i in $(seq 1 90); do
        docker exec "$OS_CONTAINER" curl -fs localhost:9200 >/dev/null 2>&1 && break
        sleep 2
    done
    docker exec "$OS_CONTAINER" curl -fs localhost:9200 >/dev/null 2>&1 || die "OpenSearch did not come up"
    log "OpenSearch is up at $OS_IP."
}

pf_ssl_yaml() {
    if $TLS; then
        printf '  ssl: true\n  ssl_certificate_file: /dp/certs/node-chain.crt\n  ssl_key_file: /dp/certs/node.key'
    else
        printf '  ssl: false'
    fi
}

# One test CA and one node certificate that is valid for every node IP and for
# localhost, so the same files serve the sources, the peer forwarder (server
# and client trust) and the admin server.
phase_generate_certs() {
    $TLS || return 0
    section "Generating test certificates"
    mkdir -p "$CERT_DIR"
    (
        cd "$CERT_DIR"
        openssl req -x509 -newkey rsa:2048 -nodes -keyout ca.key -out ca.crt -days 2 -subj "/CN=cb-test-ca" 2>/dev/null
        openssl req -newkey rsa:2048 -nodes -keyout node.key -out node.csr -subj "/CN=cb-test-node" 2>/dev/null
        printf 'subjectAltName=DNS:localhost,IP:127.0.0.1,IP:%s,IP:%s,IP:%s\nextendedKeyUsage=serverAuth,clientAuth\n' \
            "${NODE_IPS[0]}" "${NODE_IPS[1]}" "${NODE_IPS[2]}" > node.ext
        openssl x509 -req -in node.csr -CA ca.crt -CAkey ca.key -CAcreateserial -out node.crt -days 2 -extfile node.ext 2>/dev/null
        cat node.crt ca.crt > node-chain.crt
        openssl pkcs12 -export -in node.crt -inkey node.key -certfile ca.crt -out admin.p12 \
            -passout "pass:${KEY_STORE_PASSWORD}" 2>/dev/null
        chmod a+r ./*
    )
    log "CA and node certificate in $CERT_DIR (SAN: localhost, 127.0.0.1, ${NODE_IPS[*]})."
}

# $1 node, $2 usage, $3 close_usage
write_node_config() {
    local dir="$OUT_DIR/nodes/$1"
    mkdir -p "$dir/config" "$dir/pipelines"
    {
        if $TLS; then
            printf 'ssl: true\nkey_store_file_path: /dp/certs/admin.p12\nkey_store_password: %s\nprivate_key_password: %s\n' \
                "$KEY_STORE_PASSWORD" "$KEY_STORE_PASSWORD"
        else
            printf 'ssl: false\n'
        fi
        cat <<YAML
metric_registries: [Prometheus]
circuit_breakers:
  heap:
    usage: $2
    close_usage: $3
    reset: 2s
    check_interval: 500ms
YAML
        if (( NODE_COUNT == 3 )); then
            cat <<YAML
peer_forwarder:
  discovery_mode: static
  static_endpoints: ["${NODE_IPS[0]}", "${NODE_IPS[1]}", "${NODE_IPS[2]}"]
$(pf_ssl_yaml)
  buffer_size: ${PF_BUFFER_SIZE}
  forwarding_batch_size: ${PF_FORWARDING_BATCH_SIZE}
  forwarding_batch_timeout: ${PF_FORWARDING_BATCH_TIMEOUT}
YAML
        else
            # otel_traces always starts the peer forwarder server; give it the
            # test certificate or disable TLS, the default certificate from
            # config/ is not mounted.
            printf 'peer_forwarder:\n%s\n' "$(pf_ssl_yaml)"
        fi
    } > "$dir/config/data-prepper-config.yaml"
    {
        printf '%s:\n  source:\n    %s:\n' "$PIPELINE" "$PLUGIN"
        if $TLS; then
            printf '      ssl: true\n      sslKeyCertChainFile: /dp/certs/node-chain.crt\n      sslKeyFile: /dp/certs/node.key\n'
        else
            printf '      ssl: false\n'
        fi
        printf '      health_check_service: true\n'
        [[ -n "$SOURCE_EXTRA" ]] && printf '%s\n' "$SOURCE_EXTRA"
        [[ -n "$PROCESSOR" ]] && printf '  processor:\n    - %s:\n' "$PROCESSOR"
        printf '  sink:\n    - opensearch:\n        hosts: [ "http://%s:9200" ]\n        insecure: true\n        index: otel-%s\n' "$OS_IP" "$SIGNAL"
    } > "$dir/pipelines/pipelines.yaml"
    cat > "$dir/config/log4j2-rolling.properties" <<'PROPS'
status = error
dest = err
name = PropertiesConfig
appender.console.type = Console
appender.console.name = STDOUT
appender.console.layout.type = PatternLayout
appender.console.layout.pattern = %d{ISO8601} [%t] %-5p %40C - %m%n
rootLogger.level = warn
rootLogger.appenderRef.stdout.ref = STDOUT
logger.breaker.name = org.opensearch.dataprepper.core.breaker
logger.breaker.level = info
logger.plugins.name = org.opensearch.dataprepper.plugins
logger.plugins.level = info
logger.pfservice.name = org.opensearch.dataprepper.core.peerforwarder.server
logger.pfservice.level = debug
PROPS
}

# $1 index into NODES, $2 heap
start_node() {
    local n="${NODES[$1]}" dir="$OUT_DIR/nodes/${NODES[$1]}"
    docker run -d --name "$(container "$n")" --network "$NET_NAME" --ip "${NODE_IPS[$1]}" \
        -p "${SOURCE_HOST_PORTS[$1]}:${SRC_PORT}" -p "${ADMIN_HOST_PORTS[$1]}:4900" -w /tmp \
        -v "$DP_HOME/bin:/dp/bin:ro" -v "$DP_HOME/lib:/dp/lib:ro" \
        -v "$dir/config:/dp/config:ro" -v "$dir/pipelines:/dp/pipelines:ro" \
        $($TLS && echo "-v $CERT_DIR:/dp/certs:ro" || true) \
        -e JAVA_OPTS="-Xms$2 -Xmx$2" "$JRE_IMAGE" /dp/bin/data-prepper >/dev/null
}

# $1 index into NODES
wait_for_node() {
    local i n="${NODES[$1]}"
    for i in $(seq 1 120); do
        if [[ "$(grpc_health "${SOURCE_HOST_PORTS[$1]}")" == "200/0" ]]; then
            log "$n is ready (source and health check up)."
            return 0
        fi
        docker ps --format '{{.Names}}' | grep -qx "$(container "$n")" \
            || { docker logs "$(container "$n")" 2>&1 | tail -30 >&2; die "$n exited during startup"; }
        sleep 1
    done
    die "$n did not become ready"
}

phase_start_nodes() {
    section "Starting Data Prepper node(s)"
    if (( NODE_COUNT == 1 )); then
        write_node_config dp1 "$USAGE" "$CLOSE_USAGE"
        start_node 0 "$DP_HEAP"
        wait_for_node 0
        return
    fi
    local u3="${DP3_USAGE:-240mb}" c3="${DP3_CLOSE:-220mb}"
    [[ -z "${DP3_USAGE:-}" ]] && log "dp3 starts with high thresholds ($u3/$c3) for calibration."
    write_node_config dp1 400mb 300mb
    write_node_config dp2 400mb 300mb
    write_node_config dp3 "$u3" "$c3"
    start_node 0 512m; start_node 1 512m; start_node 2 256m
    wait_for_node 0; wait_for_node 1; wait_for_node 2
}

phase_calibrate_dp3() {
    (( NODE_COUNT == 3 )) || return 0
    if [[ -n "${DP3_USAGE:-}" ]]; then
        [[ -n "${DP3_CLOSE:-}" ]] || die "DP3_CLOSE must be set together with DP3_USAGE"
        log "Using DP3_USAGE=$DP3_USAGE DP3_CLOSE=$DP3_CLOSE (no calibration)."
        return 0
    fi
    section "Calibrating dp3's breaker (${CALIBRATION_SECS}s at ${STEADY_RATE} traces/s)"
    telemetrygen traces --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[0]}" "${TG_TLS[@]}" \
        --workers 2 --rate "$STEADY_RATE" --duration "${CALIBRATION_SECS}s" > "$OUT_DIR/telem-calibration.log" 2>&1 &
    local tg=$! peak=0 h i
    for i in $(seq 1 $((CALIBRATION_SECS * 2))); do
        h="$(mib "$(metric "${ADMIN_HOST_PORTS[2]}" '^core_circuitBreakers_heap_memoryUsage')")"
        if (( h > peak )); then peak=$h; fi
        sleep 0.5
    done
    wait "$tg" 2>/dev/null || true
    (( peak > 0 )) || die "Could not read dp3's heap during calibration"
    DP3_USAGE="$(( peak * 85 / 100 ))mb"
    DP3_CLOSE="$(( peak * 70 / 100 ))mb"
    log "dp3 heap peaked at ${peak} MB -> usage=$DP3_USAGE close_usage=$DP3_CLOSE. Restarting dp3..."
    docker rm -f "$(container dp3)" >/dev/null
    write_node_config dp3 "$DP3_USAGE" "$DP3_CLOSE"
    start_node 2 256m
    wait_for_node 2
    sleep 5
}

phase_check_startup() {
    section "Startup checks"
    local n line logs
    for n in "${NODES[@]}"; do
        logs="$(docker logs "$(container "$n")" 2>&1)"
        line="$(printf '%s\n' "$logs" | grep -oE 'Circuit breaker heap open threshold is [0-9.]+ MiB \([0-9]+ bytes\), close threshold is [0-9.]+ MiB \([0-9]+ bytes\)' | tail -1 || true)"
        if [[ -n "$line" ]]; then pass "$n: $line"; else fail "$n: breaker thresholds missing from the startup log."; fi
        if printf '%s\n' "$logs" | grep -q 'Installing circuit-breaker HTTP decorator'; then
            pass "$n installed the circuit-breaker HTTP decorator."
        else
            fail "$n did not log 'Installing circuit-breaker HTTP decorator'."
        fi
    done
    if [[ "$SOURCE" == logs ]]; then
        if docker logs "$(container dp1)" 2>&1 | grep -q 'Configuring HTTP service under /v1/logs'; then
            pass "Additional HTTP service registered under /v1/logs."
        else
            fail "No 'Configuring HTTP service under /v1/logs' in the log: http_path was ignored."
        fi
    fi
}

