main() {
    if $CLEANUP_ONLY; then
        section "Cleanup only"
        remove_everything
        log "Removed test containers and network $NET_NAME (if present)."
        exit 0
    fi
    phase_check_prereqs
    trap cleanup EXIT INT TERM
    $SKIP_BUILD || phase_build
    phase_locate_dp_home
    phase_start_opensearch
    phase_generate_certs
    phase_start_nodes
    phase_calibrate_dp3
    phase_check_startup
    if (( NODE_COUNT == 1 )); then
        phase_baseline_single
        phase_trip_single
        phase_settle_single
        phase_extract_events
        phase_evaluate_single
    else
        phase_measure_multi
        phase_extract_events
        phase_evaluate_multi
    fi
    log "Samples: $OUT_DIR/samples.tsv  Events: $OUT_DIR/events.tsv"

    section "Summary"
    if (( FAILURES == 0 )); then
        if (( WARNINGS == 0 )); then
            printf '%s🎉 All assertions PASSED%s\n' "$C_GRN$C_BLD" "$C_RESET"
        else
            printf '%s🎉 All assertions PASSED%s (%d warning(s) — see above)\n' "$C_GRN$C_BLD" "$C_RESET" "$WARNINGS"
        fi
        exit 0
    fi
    printf '%s❌ %d assertion(s) FAILED%s — see %s\n' "$C_RED$C_BLD" "$FAILURES" "$C_RESET" "$OUT_DIR"
    exit 1
}

main "$@"
