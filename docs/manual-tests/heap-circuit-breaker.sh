    readonly SOURCE_HOST_PORTS=("$SRC_PORT")
else
    readonly SOURCE_HOST_PORTS=(21890 21892 21893)
fi
readonly GRPC_HEALTH_PATH="/grpc.health.v1.Health/Check"
