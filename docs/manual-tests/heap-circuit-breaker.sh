phase_evaluate_single() {
    section "Results"
    local s="$OUT_DIR/samples.tsv" ev="$OUT_DIR/events.tsv"
    local open_bytes close_bytes trips first_trip last_close oc pc hc
    open_bytes="$(bytes "$USAGE")"; close_bytes="$(bytes "$CLOSE_USAGE")"
    trips="$(awk -F'\t' '$2=="open"' "$ev" | wc -l)"
    first_trip="$(awk -F'\t' '$2=="open"{print $3; exit}' "$ev")"
    last_close="$(awk -F'\t' '$2=="closed"{v=$3} END{print v}' "$ev")"
    oc="$(col "$s" dp1_open)"; pc="$(col "$s" probe)"; hc="$(col "$s" health)"

    if (( trips > 0 )) && (( ${first_trip:-0} > open_bytes )); then
        pass "Breaker tripped $trips time(s); first at $first_trip bytes (> $open_bytes)."
    else
        fail "Breaker did not trip above $open_bytes bytes (trips: $trips). Raise LOAD_RATE or lower USAGE."
    fi
    local open_samples p1 p2_probe other
    read -r open_samples p1 p2_probe other < <(awk -F'\t' -v o="$oc" -v p="$pc" 'NR>1 { if ($o+0==1) n++; if ($p=="p1") a++; if ($p=="p2") b++; if ($p=="other") c++ } END { printf "%d %d %d %d\n", n, a, b, c }' "$s")
    if (( open_samples > 0 )); then pass "Gauge core_circuitBreakers_heap_open=1 in $open_samples samples."; else warn "No sample caught the gauge at 1."; fi
    if (( p1 > 0 )); then
        pass "P1: probe to ${PROBE_PATH} was rejected $p1 time(s) by the decorator ($( [[ "$PROBE" == grpc ]] && echo "RESOURCE_EXHAUSTED" || echo "HTTP 429"))."
    else
        fail "P1: probe was never rejected by the decorator while the breaker was open."
    fi
    (( other == 0 )) || warn "$other probe answer(s) were neither OK nor a decorator rejection (connection resets under load are usually harmless)."

    if [[ -n "$P2_SERVICE" ]]; then
        local after delta buffer_timeouts timed_out inferred
        after="$(metric "${ADMIN_HOST_PORTS[0]}" "^${PIPELINE//-/_}_.*_requestTimeouts_total")"
        delta="$(awk -v a="${after:-0}" -v b="${BASE_TIMEOUTS:-0}" 'BEGIN{printf "%d", a-b}')"
        buffer_timeouts="$({ grep -A1 "${P2_SERVICE} - Failed to write the request" "$OUT_DIR/dp1.log" || true; } | grep -c 'TimeoutException' || true)"
        timed_out="$(count_in "$OUT_DIR/dp1.log" 'timed out')"
        inferred=$(( delta - ${buffer_timeouts:-0} ))
        log "P2 inputs: requestTimeouts +$delta, buffer-level TimeoutExceptions $buffer_timeouts, 'timed out' lines $timed_out, probe answers 'p2': $p2_probe"
        if (( p2_probe > 0 )); then
            pass "P2: probe received 'Circuit breaker is open.' $p2_probe time(s)."
        elif (( inferred > 0 && ${timed_out:-0} == 0 )); then
            pass "P2: $inferred request(s) rejected with a timeout status without a buffer-level log line."
        else
            warn "P2 not observed in this run (it only covers a short race window); covered by ${P2_SERVICE}Test."
        fi
    else
        log "P2: not applicable to the trace source (OTelTraceGrpcService has no pre-parse check)."
    fi

    local h_open h_open_rejected
    read -r h_open h_open_rejected < <(awk -F'\t' -v o="$oc" -v h="$hc" 'NR>1 && $o+0==1 { n++; if ($h ~ /\/8$/) a++ } END { printf "%d %d\n", n, a }' "$s")
    if (( h_open_rejected > 0 )); then pass "gRPC health check answered RESOURCE_EXHAUSTED in $h_open_rejected of $h_open open samples."; else warn "No sample caught the health check while open."; fi

    if [[ -n "$last_close" ]] && (( last_close <= close_bytes )); then
        pass "P3: last close at $last_close bytes (<= close threshold $close_bytes)."
    else
        fail "P3: last close at '${last_close:-none}' bytes (expected <= $close_bytes)."
    fi
}

phase_evaluate_multi() {
    section "Results"
    local s="$OUT_DIR/samples.tsv" ev="$OUT_DIR/events.tsv"
    local trips p4 req_failed failed ok queue drop drop_n local_after inbound=0 n c
    trips="$(awk -F'\t' '$2=="open"' "$ev" | wc -l)"
    p4="$(awk -F'\t' '$2=="p4_reject"' "$ev" | wc -l)"
    req_failed="$(awk -v a="$(metric "${ADMIN_HOST_PORTS[0]}" 'core_peerForwarder_requestsFailed_total')" -v b="${BASE_REQ_FAILED:-0}" 'BEGIN{printf "%d", a-b}')"
    failed="$(awk -v a="$(metric "${ADMIN_HOST_PORTS[0]}" 'recordsFailedForwarding_total')" -v b="${BASE_FAILED:-0}" 'BEGIN{printf "%d", a-b}')"
    ok="$(awk -v a="$(metric "${ADMIN_HOST_PORTS[0]}" 'recordsSuccessfullyForwarded_total')" -v b="${BASE_OK:-0}" 'BEGIN{printf "%d", a-b}')"
    queue="$(awk -F'\t' '$2=="queue_full"{s+=$3} END{printf "%d", s}' "$ev")"
    drop="$(awk -F'\t' '$2=="drop"{s+=$3} END{printf "%d", s}' "$ev")"
    drop_n="$(awk -F'\t' '$2=="drop"' "$ev" | wc -l)"
    local_after=$(( failed - queue - drop )); if (( local_after < 0 )); then local_after=0; fi
    for n in "${NODES[@]}"; do
        c="$(count_in "$OUT_DIR/$n.log" 'PeerForwarderHttpService - Failed to write')"; inbound=$(( inbound + ${c:-0} ))
    done

    log "dp3 thresholds: usage=${DP3_USAGE} close_usage=${DP3_CLOSE}"
    log "dp3 breaker trips: $trips, P4 rejections by dp3: $p4, failed requests at dp1: $req_failed"
    log "dp1 events for other nodes: forwarded=$ok, local after failed request=$local_after, local because queue full=$queue, dropped=$drop ($drop_n batches)"
    log "inbound write failures on all receivers: $inbound"

    if (( trips > 0 )); then
        pass "dp3's breaker tripped $trips time(s)."
    else
        fail "dp3's breaker never tripped. Set DP3_USAGE/DP3_CLOSE closer to dp3's heap, or raise STEADY_RATE."
    fi
    if [[ "$SCENARIO" == load-wave ]]; then
        log "load-wave is observational: forwarding numbers above are reported, not asserted."
        return 0
    fi
    if (( p4 == req_failed )); then
        pass "Every failed forward from dp1 is a P4 rejection by dp3 ($p4 = $req_failed)."
    else
        fail "P4 rejections ($p4) != failed requests at dp1 ($req_failed): another failure source is present."
    fi
    (( p4 > 0 )) || warn "No forwarding request hit an open window of dp3 (P4 not exercised). Raise STEADY_SECS."
    if (( drop == 0 )); then pass "Nothing was dropped."; else fail "dp1 dropped $drop records in $drop_n batches."; fi
    if (( queue == 0 && inbound == 0 )); then
        pass "No full batching queue and no inbound write failures: the test is isolated."
    else
        fail "Other failure sources present (queue full: $queue records, inbound write failures: $inbound). Lower STEADY_RATE."
    fi
    local oc hc h_open h_open_rejected h_closed h_closed_ok
    oc="$(col "$s" dp3_open)"; hc="$(col "$s" health)"
    read -r h_open h_open_rejected h_closed h_closed_ok < <(awk -F'\t' -v o="$oc" -v h="$hc" 'NR>1 { if ($o+0==1) { n++; if ($h ~ /\/8$/) a++ } else if ($o!="") { c++; if ($h=="200/0") b++ } } END { printf "%d %d %d %d\n", n, a, c, b }' "$s")
    if (( h_open_rejected > 0 )); then
        pass "dp3's gRPC health check answered RESOURCE_EXHAUSTED in $h_open_rejected of $h_open samples while open."
    else
        warn "No sample caught dp3's health check during an open window ($h_open open samples)."
    fi
    if (( h_closed > 0 && h_closed_ok * 100 / h_closed >= 90 )); then
        pass "dp3's gRPC health check answered OK in $h_closed_ok of $h_closed samples while closed."
    else
        fail "dp3's gRPC health check answered OK in only $h_closed_ok of $h_closed closed samples."
    fi
}

