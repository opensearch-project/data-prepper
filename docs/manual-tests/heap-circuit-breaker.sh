scrape() { curl -s "${CURL_TLS[@]}" --max-time 2 "${SCHEME}://localhost:$1/metrics/prometheus" 2>/dev/null || true; }
pick()   { printf '%s\n' "$1" | awk -v r="$2" '$1 ~ r { print $2; exit }' || true; }
metric() { pick "$(scrape "$1")" "$2"; }
mib()    { awk -v b="${1:-0}" 'BEGIN { printf "%d", b / 1048576 }'; }
bytes()  { awk -v v="$1" 'BEGIN { sub(/mb$/, "", v); printf "%d", v * 1048576 }'; }
since()  { awk -v a="$(date +%s.%N)" -v b="$1" 'BEGIN { printf "%.2f", a - b }'; }
count_in() { grep -cE "$2" "$1" 2>/dev/null || true; }

# Column index of header $2 in TSV file $1.
col() { head -1 "$1" | tr '\t' '\n' | grep -nx "$2" | cut -d: -f1; }

# Raw gRPC health check against a host port. Echoes "<http status>/<grpc-status>".
grpc_health() {
    printf '\x00\x00\x00\x00\x00' | curl -s "${H2[@]}" "${CURL_TLS[@]}" --max-time 2 -o /dev/null -D - -X POST \
        -H 'content-type: application/grpc' -H 'te: trailers' --data-binary @- \
        "${SCHEME}://localhost:$1${GRPC_HEALTH_PATH}" 2>/dev/null | tr -d '\r' \
        | awk '/^HTTP\//{s=$2} /^grpc-status:/{g=$2} END{printf "%s/%s", (s?s:"000"), (g==""?"-":g)}' || true
}

# One request to the source's export endpoint on host port $1. Echoes:
#   ok      accepted
#   p1      rejected by the circuit-breaker decorator (P1): HTTP 429, or gRPC
#           RESOURCE_EXHAUSTED with the decorator's message
#   p2      RESOURCE_EXHAUSTED "Circuit breaker is open." (P2, gRPC probe only)
#   buffer  RESOURCE_EXHAUSTED from CircuitBreakingBuffer (gRPC probe only)
#   other   anything else
probe_once() {
    if [[ "$PROBE" == http-json ]]; then
        local code
        code="$(curl -s "${CURL_TLS[@]}" -o /dev/null -w '%{http_code}' --max-time 3 -X POST -H 'Content-Type: application/json' \
            -d '{}' "${SCHEME}://localhost:$1${PROBE_PATH}" 2>/dev/null || true)"
        case "$code" in 200) echo ok ;; 429) echo p1 ;; *) echo other ;; esac
    else
        printf '\x00\x00\x00\x00\x00' | curl -s "${H2[@]}" "${CURL_TLS[@]}" --max-time 3 -o /dev/null -D - -X POST \
            -H 'content-type: application/grpc' -H 'te: trailers' --data-binary @- \
            "${SCHEME}://localhost:$1${PROBE_PATH}" 2>/dev/null | tr -d '\r' | awk '
            /^HTTP\// { status = $2 }
            /^grpc-status:/ { grpc = $2 }
            /^grpc-message:/ { sub(/^grpc-message: /, ""); message = $0 }
            END {
                if (grpc == "0") print "ok"
                else if (grpc == "8" && message ~ /before(%20| )reading/) print "p1"
                else if (grpc == "8" && message ~ /Unable/) print "buffer"
                else if (grpc == "8" && message ~ /^Circuit(%20| )breaker(%20| )is(%20| )open\.$/) print "p2"
                else print "other"
            }' || true
    fi
}

