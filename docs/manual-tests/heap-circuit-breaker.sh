sampler() {
    set +e
    local t0=$1 i h n bodies=()
    printf 't'
    for n in "${NODES[@]}"; do printf '\t%s_heap\t%s_open' "$n" "$n"; done
    printf '\tfwd_ok\tfwd_failed\tfwd_req_failed\tprobe\thealth'
    for n in "${NODES[@]}"; do printf '\t%s_rb' "$n"; done
    printf '\n'
    local health_port="${SOURCE_HOST_PORTS[$((NODE_COUNT - 1))]}"
    while [[ ! -f "$OUT_DIR/stop" ]]; do
        bodies=()
        for i in "${!NODES[@]}"; do bodies+=("$(scrape "${ADMIN_HOST_PORTS[$i]}")"); done
        printf '%s' "$(since "$t0")"
        for i in "${!NODES[@]}"; do
            printf '\t%s\t%s' "$(pick "${bodies[$i]}" '^core_circuitBreakers_heap_memoryUsage')" "$(pick "${bodies[$i]}" '^core_circuitBreakers_heap_open')"
        done
        printf '\t%s\t%s\t%s' "$(pick "${bodies[0]}" 'recordsSuccessfullyForwarded_total')" \
            "$(pick "${bodies[0]}" 'recordsFailedForwarding_total')" "$(pick "${bodies[0]}" 'core_peerForwarder_requestsFailed_total')"
        if (( NODE_COUNT == 1 )); then printf '\t%s' "$(probe_once "${SOURCE_HOST_PORTS[0]}")"; else printf '\t-'; fi
        printf '\t%s' "$(grpc_health "$health_port")"
        for i in "${!NODES[@]}"; do printf '\t%s' "$(pick "${bodies[$i]}" 'peerForwarder_.*_bufferUsage')"; done
        printf '\n'
        sleep 0.5
    done
}

start_sampler() {
    rm -f "$OUT_DIR/stop"
    T0="$(date +%s.%N)"; echo "$T0" > "$OUT_DIR/t0"
    SINCE="$(date -u +%Y-%m-%dT%H:%M:%S)"
    sampler "$T0" > "$OUT_DIR/samples.tsv" &
    SAMPLER_PID=$!
}

stop_sampler() {
    touch "$OUT_DIR/stop"; wait "$SAMPLER_PID" 2>/dev/null || true
    local n
    for n in "${NODES[@]}"; do docker logs --since "$SINCE" "$(container "$n")" > "$OUT_DIR/$n.log" 2>&1 || true; done
}

# Gauge value of node index $1 (default 0).
open_gauge() { metric "${ADMIN_HOST_PORTS[${1:-0}]}" '^core_circuitBreakers_heap_open'; }
is_open() { awk -v v="${1:-0}" 'BEGIN { exit (v + 0 == 1) ? 0 : 1 }'; }

phase_baseline_single() {
    section "Baseline: breaker closed, endpoint accepting"
    timeout --foreground --kill-after=5s 25s telemetrygen "$SIGNAL" --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[0]}" "${TG_TLS[@]}" \
        --duration 5s --rate 10 --workers 1 > "$OUT_DIR/telem-baseline.log" 2>&1 || true
    local v p
    v="$(open_gauge)"
    if is_open "$v"; then fail "core_circuitBreakers_heap_open=$v before any load; raise USAGE."; else pass "Breaker closed at baseline (gauge=${v:-?})."; fi
    p="$(probe_once "${SOURCE_HOST_PORTS[0]}")"
    if [[ "$p" == ok ]]; then pass "Probe to ${PROBE_PATH} accepted."; else fail "Probe to ${PROBE_PATH} answered '$p' while the breaker is closed."; fi
}

phase_trip_single() {
    section "Tripping the breaker (${LOAD_WORKERS} workers, ${LOAD_RATE}/s, ${LOAD_DURATION}s of ${SIGNAL})"
    BASE_TIMEOUTS="$(metric "${ADMIN_HOST_PORTS[0]}" "^${PIPELINE//-/_}_.*_requestTimeouts_total")"
    start_sampler
    timeout --foreground --kill-after=10s "$((LOAD_DURATION + 30))s" telemetrygen "$SIGNAL" \
        --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[0]}" "${TG_TLS[@]}" \
        --workers "$LOAD_WORKERS" --rate "$LOAD_RATE" --duration "${LOAD_DURATION}s" > "$OUT_DIR/telem-load.log" 2>&1 || true
}

phase_settle_single() {
    section "Hysteresis (P3): waiting for the breaker to settle closed"
    local stable=0 i v=""
    for i in $(seq 1 90); do
        v="$(open_gauge)"
        if [[ -n "$v" ]] && ! is_open "$v"; then stable=$((stable + 1)); (( stable >= 3 )) && break; else stable=0; fi
        sleep 1
    done
    if (( stable >= 3 )); then pass "Breaker settled closed (gauge=$v for ${stable}s)."; else fail "Breaker did not settle closed within 90s."; fi

    section "Recovery: low traffic must not reopen the breaker"
    timeout --foreground --kill-after=5s 25s telemetrygen "$SIGNAL" --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[0]}" "${TG_TLS[@]}" \
        --duration 10s --rate 20 --workers 2 > "$OUT_DIR/telem-recovery.log" 2>&1 || true
    sleep 2
    local v1 v2 p
    v1="$(open_gauge)"; sleep 3; v2="$(open_gauge)"
    if [[ -n "$v1" && -n "$v2" ]] && ! is_open "$v1" && ! is_open "$v2"; then
        pass "Breaker stayed closed under recovery traffic (gauge=$v1 → $v2)."
    else
        fail "Breaker reopened under recovery traffic (gauge=$v1 → $v2)."
    fi
    p="$(probe_once "${SOURCE_HOST_PORTS[0]}")"
    if [[ "$p" == ok ]]; then pass "Probe accepted again after recovery."; else fail "Probe answered '$p' after recovery."; fi
    stop_sampler
}

phase_measure_multi() {
    section "Measuring (${STEADY_RATE} traces/s to dp1 for ${STEADY_SECS}s$( (( FLOOD_RATE > 0 )) && echo ", flood ${FLOOD_RATE}/s on dp3 from 15s"))"
    BASE_REQ_FAILED="$(metric "${ADMIN_HOST_PORTS[0]}" 'core_peerForwarder_requestsFailed_total')"
    BASE_FAILED="$(metric "${ADMIN_HOST_PORTS[0]}" 'recordsFailedForwarding_total')"
    BASE_OK="$(metric "${ADMIN_HOST_PORTS[0]}" 'recordsSuccessfullyForwarded_total')"
    start_sampler
    telemetrygen traces --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[0]}" "${TG_TLS[@]}" \
        --workers 2 --rate "$STEADY_RATE" --duration "${STEADY_SECS}s" > "$OUT_DIR/telem-steady.log" 2>&1 &
    local steady=$!
    if (( FLOOD_RATE > 0 )); then
        sleep 15
        timeout --foreground --kill-after=10s 90s telemetrygen traces --otlp-endpoint "localhost:${SOURCE_HOST_PORTS[2]}" "${TG_TLS[@]}" \
            --workers 100 --rate "$FLOOD_RATE" --duration 25s > "$OUT_DIR/telem-flood.log" 2>&1 || true
    fi
    wait "$steady" 2>/dev/null || true
    log "Load finished. Sampling 15 s more so forwarding can settle..."
    sleep 15
    stop_sampler
}

phase_extract_events() {
    local f label re
    : > "$OUT_DIR/events.tsv"
    while IFS='|' read -r f label re; do
        [[ -f "$OUT_DIR/$f" ]] || continue
        { grep -E "$re" "$OUT_DIR/$f" 2>/dev/null || true; } | while IFS= read -r line; do
            local ts e
            ts="$(echo "$line" | cut -c1-23 | tr ',' '.')"
            e="$(date -u -d "${ts/T/ } UTC" +%s.%N 2>/dev/null)" || continue
            printf '%s\t%s\t%s\n' "$(awk -v a="$e" -v b="$T0" 'BEGIN{printf "%.2f", a-b}')" "$label" \
                "$(echo "$line" | grep -oE 'Failed to add [0-9]+ records|Dropping [0-9]+ records|MiB \([0-9]+ bytes\) used' | grep -oE '[0-9]+' | head -1 || true)"
        done
    done <<EOF >> "$OUT_DIR/events.tsv"
${NODES[$((NODE_COUNT - 1))]}.log|open|tripped and open
${NODES[$((NODE_COUNT - 1))]}.log|closed|Circuit breaker closed
${NODES[$((NODE_COUNT - 1))]}.log|p4_reject|Rejecting peer forwarder request
dp1.log|queue_full|Failed to add [0-9]+ records to the batching queue
dp1.log|send_error|Unable to (send|submit) request
dp1.log|drop|Dropping [0-9]+ records
EOF
    sort -n -o "$OUT_DIR/events.tsv" "$OUT_DIR/events.tsv"
}

