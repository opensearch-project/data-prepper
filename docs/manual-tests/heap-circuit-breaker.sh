fi
CALIBRATION_SECS="${CALIBRATION_SECS:-30}"
PF_BUFFER_SIZE="${PF_BUFFER_SIZE:-2048}"
PF_FORWARDING_BATCH_SIZE="${PF_FORWARDING_BATCH_SIZE:-500}"
PF_FORWARDING_BATCH_TIMEOUT="${PF_FORWARDING_BATCH_TIMEOUT:-500ms}"
NET_PREFIX="${NET_PREFIX:-172.28.0}"
JRE_IMAGE="${JRE_IMAGE:-eclipse-temurin:17-jre}"
if (( NODE_COUNT == 1 )); then
    OUT_DIR="${OUT_DIR:-/tmp/cb-test-${SOURCE}-n1$($TLS && echo -tls || true)}"
else
    OUT_DIR="${OUT_DIR:-/tmp/cb-test-${SOURCE}-n3-${SCENARIO}$($TLS && echo -tls || true)}"
fi

