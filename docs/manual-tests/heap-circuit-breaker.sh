warn()    { printf '%s⚠  WARN%s %s\n' "$C_YEL" "$C_RESET" "$*"; WARNINGS=$((WARNINGS + 1)); }
die()     { printf '%sERROR%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; exit 2; }

# ---------- Cleanup ----------
container() { printf 'cb-test-%s' "$1"; }

remove_everything() {
    touch "$OUT_DIR/stop" 2>/dev/null || true
    local n
    for n in "${ALL_NODES[@]}"; do docker rm -f "$(container "$n")" >/dev/null 2>&1 || true; done
    docker rm -f "$OS_CONTAINER" >/dev/null 2>&1 || true
    docker network rm "$NET_NAME" >/dev/null 2>&1 || true
}

cleanup() {
    local rc=$?
    set +e
    trap - EXIT INT TERM
    touch "$OUT_DIR/stop" 2>/dev/null
    if $KEEP_RUNNING; then
        log "Leaving containers running. Cleanup later with: $0 --cleanup"
    else
        log "Removing containers and network..."
        remove_everything
    fi
    exit "$rc"
}

# =============================================================================
# Helpers
